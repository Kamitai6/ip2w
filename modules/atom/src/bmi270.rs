/// Accelerometer output data rate
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[repr(u8)]
pub enum AccOdr {
    Hz0_78 = 0x01,
    Hz1_56 = 0x02,
    Hz3_12 = 0x03,
    Hz6_25 = 0x04,
    Hz12_5 = 0x05,
    Hz25 = 0x06,
    Hz50 = 0x07,
    #[default]
    Hz100 = 0x08,
    Hz200 = 0x09,
    Hz400 = 0x0A,
    Hz800 = 0x0B,
    Hz1600 = 0x0C,
}

/// Accelerometer range
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[repr(u8)]
pub enum AccRange {
    /// ±2g
    G2 = 0x00,
    /// ±4g
    #[default]
    G4 = 0x01,
    /// ±8g
    G8 = 0x02,
    /// ±16g
    G16 = 0x03,
}

impl AccRange {
    /// Returns sensitivity in LSB/g
    pub fn sensitivity(self) -> f32 {
        match self {
            AccRange::G2 => 16384.0,
            AccRange::G4 => 8192.0,
            AccRange::G8 => 4096.0,
            AccRange::G16 => 2048.0,
        }
    }
}

/// Gyroscope output data rate
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[repr(u8)]
pub enum GyrOdr {
    Hz25 = 0x06,
    Hz50 = 0x07,
    Hz100 = 0x08,
    #[default]
    Hz200 = 0x09,
    Hz400 = 0x0A,
    Hz800 = 0x0B,
    Hz1600 = 0x0C,
    Hz3200 = 0x0D,
}

/// Gyroscope range
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[repr(u8)]
pub enum GyrRange {
    /// ±2000 °/s
    #[default]
    Dps2000 = 0x00,
    /// ±1000 °/s
    Dps1000 = 0x01,
    /// ±500 °/s
    Dps500 = 0x02,
    /// ±250 °/s
    Dps250 = 0x03,
    /// ±125 °/s
    Dps125 = 0x04,
}

impl GyrRange {
    /// Returns sensitivity in LSB/(°/s)
    pub fn sensitivity(self) -> f32 {
        match self {
            GyrRange::Dps2000 => 16.4,
            GyrRange::Dps1000 => 32.8,
            GyrRange::Dps500 => 65.6,
            GyrRange::Dps250 => 131.2,
            GyrRange::Dps125 => 262.4,
        }
    }
}

